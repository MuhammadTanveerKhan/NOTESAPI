const express = require("express")
const  postnotes  = require("../controllers/post.controller")
const { getapi } = require("../controllers/get.controller")
const {getbyid} = require("../controllers/param.controller")
const update = require("../controllers/upadate.controller")
const { route } = require("../app")
const deletenote = require("../controllers/delete.controller")
const regapi = require("../controllers/reg.controller")
const loginapi = require("../controllers/login.controller")
const authmiddleware = require("../controllers/middlewares/auth.middleware")
const router = express.Router()

router.post("/post",authmiddleware,postnotes)
router.get("/get",authmiddleware,getapi)
router.get("/:id",authmiddleware,getbyid)
router.put("/:id",authmiddleware,update)
router.delete("/:id",authmiddleware,deletenote)
router.post("/reg",regapi)
router.post("/login",loginapi)
module.exports=router